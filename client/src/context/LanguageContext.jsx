export function LanguageProvider({ children }) {
 const [language, setLanguage] = useState(localStorage.getItem("easybank_language") || "en");

 function changeLanguage(value) {
 setLanguage(value);
 localStorage.setItem("easybank_language", value);
 }

 useEffect(() => {
 document.documentElement.lang = language === "kn" ? "kn" : language === "hi" ? "hi" : "en";
 document.title = "EasyBank";
 }, [language]);

 const value = useMemo(() => ({
 language,
 changeLanguage,
 t: (key) => translations[language]?.[key] ?? translations.en[key] ?? key
 }), [language]);

 return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

